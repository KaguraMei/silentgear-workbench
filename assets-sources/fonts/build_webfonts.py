"""Rebuild disjoint WOFF2 subsets; preserve every source cmap character.

Uses convert_one from the user's tff2woff2 project, copied beside this file.
Run with Python + fonttools + brotli; generated files are committed for normal builds.
"""
from pathlib import Path
from collections import Counter
import json
from fontTools.ttLib import TTFont
from ttf_to_web import convert_one

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent


def ranges(points):
    result = []
    for point in sorted(points):
        if result and point == result[-1][1] + 1:
            result[-1][1] = point
        else:
            result.append([point, point])
    return ','.join(f'U+{a:X}' + (f'-{b:X}' if a != b else '') for a, b in result)


def main():
    ui = ''.join(p.read_text(encoding='utf-8') for p in (ROOT / 'src').iterdir()
                 if p.suffix in {'.tsx', '.ts', '.js'} and p.name != 'data.js')
    core = set(map(ord, ui)) | set(range(32, 127))
    catalog = set(map(ord, (ROOT / 'src/data.js').read_text(encoding='utf-8')))
    faces, report = [], []
    for weight, css_weight in [('Medium', '100 500'), ('Bold', '600 900')]:
        filename = f'HarmonyOS_Sans_SC_{weight}.woff2'
        source = HERE / 'originals' / filename
        with TTFont(source) as font:
            coverage = set(font.getBestCmap())
        groups = {'core': coverage & core,
                  'catalog': (coverage & catalog) - core,
                  'extended': coverage - core - catalog}
        actual = set()
        for group, points in groups.items():
            output = ROOT / 'public/fonts' / group
            output.mkdir(parents=True, exist_ok=True)
            convert_one(source, output, True, False, ''.join(map(chr, sorted(points))))
            path = output / filename
            with TTFont(path) as font:
                subset_coverage = set(font.getBestCmap())
            assert subset_coverage == points, f'{weight}/{group}: unexpected cmap'
            assert not actual & subset_coverage, 'Subsets must not overlap'
            actual |= subset_coverage
            faces.append(f"""@font-face {{
  font-family: 'HarmonyOS Sans SC';
  src: url('/fonts/{group}/{filename}') format('woff2');
  font-style: normal;
  font-weight: {css_weight};
  font-display: swap;
  unicode-range: {ranges(points)};
}}""")
            report.append({'weight': weight, 'group': group, 'characters': len(points),
                           'bytes': path.stat().st_size, 'sourceBytes': source.stat().st_size})
        assert actual == coverage, f'{weight}: source character coverage lost'
    (ROOT / 'src/fonts.generated.css').write_text(
        '/* Generated by assets-sources/fonts/build_webfonts.py. Do not hand edit. */\n'
        + '\n\n'.join(faces) + '\n', encoding='utf-8')
    (ROOT / 'artifacts/font-subsets.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    print('All original character coverage preserved; six disjoint subsets generated.')


if __name__ == '__main__':
    main()
