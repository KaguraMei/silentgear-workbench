import {test,expect} from '@playwright/test';
import E from '../src/engine.js';
import {materialCandidate,blueprintCandidate,STORAGE_KEY} from '../src/comparison.js';
import {readFile} from 'node:fs/promises';

test('compare material outcomes, select a slot, set baseline, rename and persist',async({page},info)=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/');
 await page.getByLabel('主体品级').selectOption('MAX');await page.getByLabel('主体星光充能').selectOption('3');await page.locator('#wear').fill('50');
 await page.getByRole('button',{name:'对比工作台',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'配装对比工作台'});
 await dialog.getByRole('button',{name:'材料候选',exact:true}).click();
 await dialog.getByLabel('搜索候选材料').fill('iron');
 await dialog.getByRole('button',{name:'加入材料候选铁',exact:true}).click();
 await expect(dialog.getByRole('button',{name:'加入材料候选铁',exact:true})).toBeDisabled();
 await dialog.getByLabel('搜索候选材料').fill('diamond');await dialog.getByRole('button',{name:'加入材料候选钻石',exact:true}).click();
 const current=E.defaultBuild();current.parts.main.grade='MAX';current.parts.main.star=3;current.wear=50;
 const iron=E.calculate(materialCandidate(current,'main','iron')),diamond=E.calculate(materialCandidate(current,'main','diamond'));
 const attack=dialog.locator('[data-compare-stat=attack_damage]');
 const values=attack.locator('.comparison-number');
 await expect(values.nth(1)).toHaveText(new Intl.NumberFormat('zh-CN',{maximumFractionDigits:2}).format(iron.stats.attack_damage));
 await expect(values.nth(2)).toHaveText(new Intl.NumberFormat('zh-CN',{maximumFractionDigits:2}).format(diamond.stats.attack_damage));
 await dialog.getByLabel('基准',{exact:true}).selectOption({label:'主体候选 · 铁 · 剑'});
 await expect(attack.locator('td').nth(1).locator('.comparison-delta')).toHaveCount(0);
 await expect(attack.locator('td').nth(2)).toContainText('较基准 +');
 await dialog.getByLabel('比较部件',{exact:true}).selectOption('rod');
 await expect(dialog.getByRole('heading',{name:'剑 / 工具杆材料候选'})).toBeVisible();
 await expect(dialog.getByLabel('搜索候选材料')).toHaveValue('');
 await dialog.getByLabel('预览属性').selectOption('final_durability');await dialog.getByLabel('候选排序').selectOption('descending');
 const sorted=await dialog.locator('.candidate-value').evaluateAll(elements=>elements.map(el=>Number(el.firstChild!.textContent!.trim().replaceAll(',',''))));
 expect(sorted).toEqual([...sorted].sort((a,b)=>b-a));
 await page.screenshot({path:`artifacts/${info.project.name}-comparison-candidates.png`});
 await dialog.getByRole('button',{name:'重命名主体候选 · 钻石 · 剑',exact:true}).click();
 await dialog.getByLabel('编辑快照名称').fill('钻石 / 方案 A');await dialog.getByRole('button',{name:'保存名称'}).click();
 await dialog.getByLabel('只看差异').check();
 await expect(dialog.locator('.comparison-part').filter({hasText:'橡木'})).toHaveCount(0);
 await dialog.locator('.comparison-body').evaluate(element=>{const table=element.querySelector('.comparison-scroll')!;element.scrollTop+=table.getBoundingClientRect().top-element.getBoundingClientRect().top;});
 await page.screenshot({path:`artifacts/${info.project.name}-comparison-table.png`});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 const box=await dialog.boundingBox();expect(box!.x).toBeGreaterThanOrEqual(0);expect(box!.width).toBeLessThanOrEqual(page.viewportSize()!.width);
 await page.keyboard.press('Escape');await page.reload();await page.getByRole('button',{name:/^对比工作台/}).click();
 await expect(dialog.locator('thead')).toContainText('钻石 / 方案 A');
 await expect(dialog.locator('thead th')).toHaveCount(4);
 expect(errors).toEqual([]);
});

test('compare blueprints and transfer snapshots without losing existing work',async({page},info)=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/');await page.getByRole('button',{name:'对比工作台',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'配装对比工作台'});
 await dialog.getByLabel('当前配装名称').fill('原剑');await dialog.getByRole('button',{name:'保存当前配装'}).click();
 await dialog.getByLabel('其他装备蓝图').selectOption('bow');
 await expect(dialog.locator('.comparison-transfer-note')).toContainText('弓弦');
 await dialog.getByRole('button',{name:'加入蓝图对比'}).click();
 await dialog.getByLabel('其他装备蓝图').selectOption('helmet');await dialog.getByRole('button',{name:'加入蓝图对比'}).click();
 await expect(dialog.getByRole('button',{name:'加入蓝图对比'})).toBeDisabled();
 await expect(dialog.locator('[data-compare-stat=attack_damage] td').nth(3)).toHaveText('—');
 await expect(dialog.locator('[data-compare-stat=final_armor] td').nth(0)).toHaveText('—');
 const stored=JSON.parse((await page.evaluate(key=>localStorage.getItem(key),STORAGE_KEY))!);
 expect(stored.snapshots[1].build).toEqual(blueprintCandidate(E.defaultBuild(),'bow').build);
 await expect(page.getByRole('heading',{level:1})).toHaveText('强化黑曜石剑');
 await dialog.locator('.comparison-body').evaluate(element=>{const table=element.querySelector('.comparison-scroll')!;element.scrollTop+=table.getBoundingClientRect().top-element.getBoundingClientRect().top;});
 await page.screenshot({path:`artifacts/${info.project.name}-comparison-blueprints.png`});
 if(info.project.name==='mobile-chrome'){
  const rowLabel=dialog.locator('[data-compare-stat=attack_damage] th');const before=await rowLabel.boundingBox();
  await dialog.locator('.comparison-scroll').evaluate(element=>{element.scrollLeft=element.scrollWidth;});
  expect((await rowLabel.boundingBox())!.x).toBeCloseTo(before!.x,0);
  const fixed=await rowLabel.boundingBox(),last=await dialog.locator('[data-compare-stat=final_durability] td').last().boundingBox();
  expect(last!.x).toBeGreaterThanOrEqual(fixed!.x+fixed!.width-1);
  await page.screenshot({path:`artifacts/${info.project.name}-comparison-blueprints-scrolled.png`});
  const viewport=page.viewportSize()!;await page.setViewportSize({width:320,height:740});
  await dialog.locator('.comparison-scroll').evaluate(element=>{element.scrollLeft=element.scrollWidth;});
  const narrowFixed=await rowLabel.boundingBox(),narrowLast=await dialog.locator('[data-compare-stat=final_durability] td').last().boundingBox();
  expect(narrowLast!.x).toBeGreaterThanOrEqual(narrowFixed!.x+narrowFixed!.width-1);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.setViewportSize(viewport);
 }
 const downloadEvent=page.waitForEvent('download');await dialog.getByRole('button',{name:'导出快照'}).click();
 const download=await downloadEvent;expect(download.suggestedFilename()).toBe('silentgear-comparisons.json');
 await download.saveAs(`artifacts/${info.project.name}-comparisons.json`);const bytes=await readFile((await download.path())!);
 const input=dialog.getByLabel('导入对比快照文件');
 await input.setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{bad')});await expect(dialog.getByRole('status')).toContainText('导入失败');
 await expect(dialog.locator('thead th')).toHaveCount(5);
 await dialog.getByRole('button',{name:'清空快照'}).click();
 await input.setInputFiles({name:'snapshots.json',mimeType:'application/json',buffer:bytes});
 await expect(dialog.getByRole('status')).toContainText('导入 3 个快照');
 await input.setInputFiles({name:'snapshots.json',mimeType:'application/json',buffer:bytes});
 await expect(dialog.getByRole('status')).toContainText('3 个重复');
 await dialog.getByLabel('基准',{exact:true}).selectOption({label:'强化黑曜石头盔'});
 await dialog.getByRole('button',{name:'删除强化黑曜石头盔',exact:true}).click();await expect(dialog.getByLabel('基准',{exact:true})).toHaveValue('live');
 await dialog.locator('thead th').filter({hasText:'强化黑曜石弓'}).getByRole('button',{name:'应用此配装'}).click();
 await expect(dialog).not.toBeVisible();await expect(page.getByRole('heading',{level:1})).toHaveText('强化黑曜石弓');
 expect(errors).toEqual([]);
});
